export function QuickNoteBrandIcon({
  name,
  className,
  style,
}: QuickNoteBrandIconProps) {
  const brand = getQuickNoteBrand(name);
  if (!brand) return null;

  const viewBox = brand.slug === 'chatgpt' ? '0 0 512 512' : '0 0 24 24';

  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox={viewBox}
      className={className}
      style={{ ...style, color: brand.color }}
      data-quick-note-brand={brand.slug}
    >
      <BrandGlyph slug={brand.slug} />
    </svg>
  );
}
